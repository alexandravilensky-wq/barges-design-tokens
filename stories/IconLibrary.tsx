const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const fileBase = (file?: string) =>
  file
    ?.split('/')
    .pop()
    ?.replace(/(-dark)?\.svg$/, '');

/** Split sets with an option property (Direction, Sign, Country…) into one tile per option. */
function toIcons(sets: IconSet[]): Icon[] {
  return sets.flatMap(set => {
    const optionKey = Object.keys(set.files[0] ?? {}).find(k => !['file', 'Brand', 'Theme'].includes(k));
    const options = optionKey ? [...new Set(set.files.map(f => f[optionKey]))] : [undefined];
    const parts = set.name.split('/').map(s => s.trim());
    const group = parts.length > 1 ? parts[0] : undefined;
    const leaf = parts[parts.length - 1];
    return options.map(option => {
      const files = option ? set.files.filter(f => f[optionKey!] === option) : set.files;
      // An option's own code name is the one its exported file is named after (chevron-up.svg → chevronUp).
      const own = option ? set.code.filter(c => kebab(c) === fileBase(files[0]?.file)) : set.code;
      return {
        id: option ? `${set.name}|${option}` : set.name,
        // Plural sets (Flags, Press) read better as just the option: "argentina", not "flags argentina".
        name: option ? (/s$/i.test(leaf) ? option : `${leaf} ${option}`) : leaf,
        group,
        section: set.section ?? 'Other',
        code: own,
        tags: [...set.aliases, ...(group ? [group] : [])],
        note: set.note,
        color: set.color,
        files,
      };
    });
  });
}

const ICONS = toIcons(Object.values(manifests)[0] ?? []);

/** Figma sections that hold illustrations rather than icons. */
const ILLUSTRATION_SECTIONS = ['Reading Categories', 'Empty States'];
const kindOf = (i: Icon): LibraryKind => (ILLUSTRATION_SECTIONS.includes(i.section) ? 'illustrations' : 'icons');

function variantFor(icon: Icon, brand: string, theme: string) {
  const forBrand = icon.files.filter(f => !f.Brand || f.Brand === BRAND_NAMES[brand]);
  return (
    forBrand.find(f => (f.Theme ?? 'Light').toLowerCase() === theme) ??
    forBrand.find(f => !f.Theme || f.Theme === 'Light')
  );
}

const svgFor = (file?: string) => (file ? svgs[`../icons/${file}`] : undefined);

/** Natural size from the SVG, to tell icons (24px) from illustrations. */
function naturalSize(svg?: string) {
  const m = svg?.match(/viewBox="[\d.-]+ [\d.-]+ ([\d.]+) ([\d.]+)"/);
  return m ? Math.max(+m[1], +m[2]) : 24;
}

function Svg({ svg, size, color }: { svg?: string; size: number; color?: string }) {
  // Exported SVGs reuse ids like "a"; make them unique per preview so embedded images don't swap.
  const uid = useId().replace(/:/g, '');
  if (!svg) return <span className="il-missing">Not in this brand</span>;
  const html = svg
    .replace(/\bid="([^"]+)"/g, `id="$1-${uid}"`)
    .replace(/url\(#([^)]+)\)/g, `url(#$1-${uid})`)
    .replace(/href="#([^"]+)"/g, `href="#$1-${uid}"`);
  return (
    <span
      className="il-svg"
      style={{ width: size, height: size, color: `var(${color ?? '--color-icon-primary'})` }}
      // SVGs come from our own Figma export.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}

