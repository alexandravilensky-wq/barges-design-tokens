/** Library page used by Icons.stories.tsx and Illustrations.stories.tsx. */
export type LibraryKind = 'icons' | 'illustrations';

/** Shape written by scripts/export-icons.mjs. */
interface IconSet {
  name: string;
  section?: string;
  code: string[];
  aliases: string[];
  note?: string;
  color?: { figma: string; css: string };
  files: ({ file: string } & Record<string, string>)[];
}

/** One tile: a set, or one option of a set (e.g. Chevron · Up, Zodiac · Aries). */
interface Icon {
  id: string;
  name: string;
  group?: string;
  section: string;
  code: string[];
  tags: string[];
  note?: string;
  color?: IconSet['color'];
  files: IconSet['files'];
}

// Generated by `npm run export:icons`; empty until the first export.
