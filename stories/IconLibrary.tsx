const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

function Tile(props: { icon: Icon; brand: string; theme: string; onOpen: () => void; size?: number }) {
  const { icon, brand, theme, onOpen, size = 24 } = props;
  const svg = svgFor(variantFor(icon, brand, theme)?.file);
  const big = naturalSize(svg) > 32;
  return (
    <button className="il-tile" onClick={onOpen} title={[...icon.code, ...icon.tags].join(', ')}>
      <Svg svg={svg} size={big ? size * 3 : size} color={icon.color?.css} />
      <small>{icon.name.toLowerCase()}</small>
    </button>
  );
}

function Detail(props: {
  icon: Icon;
  brand: string;
  theme: string;
  onClose: () => void;
  onOpen: (i: Icon) => void;
  onTag: (t: string) => void;
}) {
  const { icon, brand, theme, onClose, onOpen, onTag } = props;
  const variant = variantFor(icon, brand, theme);
  const svg = svgFor(variant?.file);
  const big = naturalSize(svg) > 32;
  const sizes = big ? [96, 184, 256] : [16, 20, 24, 32, 48];
  const [size, setSize] = useState(big ? 184 : 24);
  const [copied, setCopied] = useState('');
  useEffect(() => setSize(big ? 184 : 24), [icon.id, big]);
  useEffect(() => {
    const esc = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', esc);
    return () => window.removeEventListener('keydown', esc);
  }, [onClose]);
  const related = ICONS.filter(
    i =>
      i.id !== icon.id &&
      kindOf(i) === kindOf(icon) &&
      (icon.group ? i.group === icon.group : i.section === icon.section),
  ).slice(0, 8);
  const copy = (text: string) => {
    navigator.clipboard?.writeText(text);
    setCopied(text);
    setTimeout(() => setCopied(''), 1200);
  };
  const CopyButton = ({ text }: { text: string }) => (
    <button className="il-copy" onClick={() => copy(text)}>
      {copied === text ? 'Copied' : 'Copy'}
    </button>
  );
  return (
    <div className="il-overlay" onClick={onClose}>
      <div className="il-modal" role="dialog" aria-label={icon.name} onClick={e => e.stopPropagation()}>
        <header>
          <div>
            <p>{[icon.section, icon.group].filter(Boolean).join(' · ')}</p>
            <h3>{icon.name.toLowerCase()}</h3>
          </div>
          <button className="il-close" onClick={onClose} aria-label="Close">
            ×
          </button>
        </header>
        <div className="il-body">
          <div className="il-row">
            <b>Size</b>
            {sizes.map(s => (
              <button key={s} className={`il-size${s === size ? ' on' : ''}`} onClick={() => setSize(s)}>
                {s}
              </button>
            ))}
          </div>
          <div className={`il-stage${big ? ' xl' : ''}`}>
            <Svg svg={svg} size={size} color={icon.color?.css} />
          </div>
          <div>
            <h4>Brands</h4>
            <div className="il-brands">
              {Object.entries(BRAND_NAMES).map(([key, label]) => (
                <div key={key}>
                  <Svg svg={svgFor(variantFor(icon, key, theme)?.file)} size={big ? 64 : 24} color={icon.color?.css} />
                  {label}
                </div>
              ))}
            </div>
          </div>
          <dl className="il-meta">
            <dt>Code</dt>
            <dd>
              {icon.code.length ? (
                icon.code.map(c => (
                  <span key={c} style={{ ...mono, marginRight: 12 }}>
                    {c}
                    <CopyButton text={c} />
                  </span>
                ))
              ) : (
                <span style={{ color: 'var(--color-text-secondary)' }}>Figma only – not in code yet</span>
              )}
            </dd>
            {variant && (
              <>
                <dt>File</dt>
                <dd style={mono}>
                  icons/{variant.file}
                  <CopyButton text={`icons/${variant.file}`} />
                </dd>
              </>
            )}
            <dt>Colour</dt>
            <dd style={mono}>{icon.color ? `${icon.color.css} (${icon.color.figma})` : 'Own colours'}</dd>
            {icon.note && (
              <>
                <dt>Note</dt>
                <dd>{icon.note}</dd>
              </>
            )}
          </dl>
          {related.length > 0 && (
            <div>
              <h4>Related icons</h4>
              <div className="il-related">
                {related.map(r => (
                  <Tile key={r.id} icon={r} brand={brand} theme={theme} onOpen={() => onOpen(r)} size={20} />
                ))}
              </div>
            </div>
          )}
          {icon.tags.length > 0 && (
            <div>
              <h4>Tags</h4>
              <div className="il-tags">
                {icon.tags.map(t => (
                  <button key={t} onClick={() => onTag(t)}>
                    {t.toLowerCase()}
                  </button>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

export function IconLibrary({ brand, theme, kind }: { brand: string; theme: string; kind: LibraryKind }) {
  const items = useMemo(() => ICONS.filter(i => kindOf(i) === kind), [kind]);
  const noun = kind === 'icons' ? 'icon' : 'illustration';
  const [query, setQuery] = useState('');
  const [open, setOpen] = useState<Icon | null>(null);
  const [active, setActive] = useState('');
  const root = useRef<HTMLDivElement>(null);

  const q = query.trim().toLowerCase();
  const shown = useMemo(
    () => items.filter(i => !q || [i.name, i.group ?? '', ...i.code, ...i.tags].some(s => s.toLowerCase().includes(q))),
    [q, items],
  );
  const sections = useMemo(() => {
    const rank = (s: string) => SECTION_ORDER.indexOf(s) + 1 || 99;
    return [...new Set(shown.map(i => i.section))].sort((a, b) => rank(a) - rank(b));
  }, [shown]);

  // Highlight the section currently in view in the side menu.
  useEffect(() => {
    const observer = new IntersectionObserver(
      entries => {
        const top = entries
          .filter(e => e.isIntersecting)
          .sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top)[0];
        if (top) setActive(top.target.id);
      },
      { rootMargin: '0px 0px -70% 0px' },
    );
    root.current?.querySelectorAll('.il-section').forEach(el => observer.observe(el));
    return () => observer.disconnect();
  }, [sections]);

  if (!items.length)
    return (
      <div className="il">
        <style>{CSS}</style>
        <p className="il-empty">
          No icons exported yet. Run the <b>Export icons</b> GitHub Action or{' '}
          <code style={mono}>npm run export:icons</code>.
        </p>
      </div>
    );

  return (
    <div className="il" ref={root}>
      <style>{CSS}</style>
      <nav className="il-nav" aria-label="Icon sections">
        <h4>Content</h4>
        {sections.map(s => (
          <a
            key={s}
            href={`#${slug(s)}`}
            className={active === slug(s) ? 'on' : ''}
            onClick={e => {
              e.preventDefault();
              document.getElementById(slug(s))?.scrollIntoView({ behavior: 'smooth' });
            }}
          >
            {s} <span>{shown.filter(i => i.section === s).length}</span>
          </a>
        ))}
      </nav>
      <main className="il-main">
        <div className="il-head">
          <h1>{kind === 'icons' ? 'Icon library' : 'Illustrations'}</h1>
          <span className="il-chip">
            {items.length} {noun}s
          </span>
        </div>
        <p className="il-lead">
          Every {noun} from the Figma DS-Foundation file, shown for <b>{BRAND_NAMES[brand]}</b> in {theme} mode. Switch
          brand and theme in the toolbar; click any {noun} for sizes, code name and tags.
        </p>
        <div className="il-searchbar">
          <label className="il-search">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <circle cx="11" cy="11" r="7" />
              <path d="m20 20-4-4" />
            </svg>
            <input
              value={query}
              onChange={e => setQuery(e.target.value)}
              placeholder={`Search ${noun}s by name, code name or keyword…`}
              aria-label={`Search ${noun}s`}
            />
          </label>
        </div>
        {!shown.length && <p className="il-empty">No icons match “{query}”.</p>}
        {sections.map(s => (
          <section key={s} id={slug(s)} className="il-section">
            <h2>{s}</h2>
            <div className={`il-grid${kind === 'illustrations' ? ' xl' : ''}`}>
              {shown
                .filter(i => i.section === s)
                .map(i => (
                  <Tile
                    key={i.id}
                    icon={i}
                    brand={brand}
                    theme={theme}
                    onOpen={() => setOpen(i)}
                    size={kind === 'illustrations' ? 56 : 24}
                  />
                ))}
            </div>
          </section>
        ))}
      </main>
      {open && (
        <Detail
          icon={open}
          brand={brand}
          theme={theme}
          onClose={() => setOpen(null)}
          onOpen={setOpen}
          onTag={t => {
            setQuery(t);
            setOpen(null);
          }}
        />
      )}
    </div>
  );
}
